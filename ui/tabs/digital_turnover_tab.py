    def closeEvent(self, event):
        """Ensure the generator thread is stopped before closing."""
        if self._generator_thread is not None:
            try:
                if self._generator_thread.isRunning():
                    self._generator_thread.requestInterruption()
                    self._generator_thread.wait(2000)
                self._generator_thread.deleteLater()
            except Exception:
                pass
            self._generator_thread = None
        super().closeEvent(event)