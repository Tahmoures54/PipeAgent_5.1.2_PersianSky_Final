    # ── DATA LOADING ─────────────────────────────────────────
    def refresh(self):
        self._set_status("Loading data...")
        QApplication.processEvents()

        try:
            with self.db.session_scope() as s:
                projects = (
                    s.query(Project)
                    .order_by(Project.project_code)
                    .all()
                )
                self._load_projects(projects)

                dossiers = (
                    s.query(TurnoverDossier)
                    .order_by(TurnoverDossier.id.desc())
                    .limit(MAX_DISPLAY_ROWS)
                    .all()
                )

                self._cached_dossiers = []
                for d in dossiers:
                    self._cached_dossiers.append({
                        "id": d.id,
                        "dossier_number": getattr(d, "dossier_number", ""),
                        "scope_key": getattr(d, "scope_key", ""),
                        "status": getattr(d, "status", ""),
                        "completeness_pct": getattr(d, "completeness_pct", 0) or 0,
                        "generated_at": str(getattr(d, "generated_at", "") or ""),
                        "generated_by": getattr(d, "generated_by", ""),
                        "generated_path": getattr(d, "generated_path", ""),
                        "notes": getattr(d, "notes", ""),
                        "project_id": getattr(d, "project_id", None),
                    })

            self._apply_filters()
            self._update_statistics()
            self._set_status(
                f"Loaded {len(self._cached_dossiers)} dossiers"
            )
        except Exception as e:
            self._set_status(f"Error loading data: {e}")
            QMessageBox.critical(
                self, "Load Error",
                f"Failed to load data:\n{str(e)}"
            )

    def _load_projects(self, projects):
        current_data = self.cmb_project.currentData()
        self.cmb_project.blockSignals(True)
        self.cmb_project.clear()
        for p in projects:
            self.cmb_project.addItem(f"{p.project_code} — {p.title}", p.id)
        if current_data is not None:
            idx = self.cmb_project.findData(current_data)
            self.cmb_project.setCurrentIndex(max(0, idx))
        self.cmb_project.blockSignals(False)

        current_filter = self.cmb_project_filter.currentData()
        self.cmb_project_filter.blockSignals(True)
        self.cmb_project_filter.clear()
        self.cmb_project_filter.addItem("All Projects", None)
        for p in projects:
            self.cmb_project_filter.addItem(
                f"{p.project_code} — {p.title}", p.id
            )
        if current_filter is not None:
            idx = self.cmb_project_filter.findData(current_filter)
            self.cmb_project_filter.setCurrentIndex(max(0, idx))
        self.cmb_project_filter.blockSignals(False)

    def _apply_filters(self):
        search_text = self.txt_search.text().strip().lower()
        status_filter = self.cmb_status_filter.currentData()
        project_filter = self.cmb_project_filter.currentData()

        filtered = []
        for d in self._cached_dossiers:
            if status_filter and d.get("status") != status_filter:
                continue
            if project_filter and d.get("project_id") != project_filter:
                continue
            if search_text:
                searchable = " ".join([
                    str(d.get("dossier_number", "")),
                    str(d.get("scope_key", "")),
                    str(d.get("generated_path", "")),
                    str(d.get("notes", "")),
                    str(d.get("generated_by", "")),
                ]).lower()
                if search_text not in searchable:
                    continue
            filtered.append(d)

        self._populate_table(filtered)

    def _populate_table(self, dossiers: list):
        self.table.setSortingEnabled(False)
        self.table.setRowCount(0)

        for d in dossiers:
            row = self.table.rowCount()
            self.table.insertRow(row)

            values = [
                str(d.get("id", "")),
                d.get("dossier_number", ""),
                d.get("scope_key", ""),
                d.get("status", ""),
                f"{d.get('completeness_pct', 0):.0f}",
                d.get("generated_at", ""),
                d.get("generated_by", ""),
                d.get("generated_path", ""),
                d.get("notes", ""),
            ]

            for col, value in enumerate(values):
                item = QTableWidgetItem(str(value))
                item.setTextAlignment(Qt.AlignmentFlag.AlignCenter)

                if col == 3:  # Status column
                    status = str(value)
                    colors = STATUS_COLORS.get(status, {})
                    if colors:
                        item.setBackground(QColor(colors["bg"]))
                        item.setForeground(QColor(colors["fg"]))
                        f = item.font()
                        f.setBold(True)
                        item.setFont(f)

                self.table.setItem(row, col, item)

            self.table.setRowHeight(row, 42)

        self.table.setSortingEnabled(True)
        self.lbl_row_count.setText(f"Rows: {self.table.rowCount()}")
        self._update_selection_count()

    def _update_statistics(self):
        total = len(self._cached_dossiers)
        complete = sum(
            1 for d in self._cached_dossiers if d.get("status") == "Complete"
        )
        partial = sum(
            1 for d in self._cached_dossiers if d.get("status") == "Partial"
        )
        draft = sum(
            1 for d in self._cached_dossiers if d.get("status") == "Draft"
        )

        avg_completeness = 0
        if total > 0:
            avg_completeness = sum(
                d.get("completeness_pct", 0)
                for d in self._cached_dossiers
            ) / total

        self.stat_total.set_value(total)
        self.stat_complete.set_value(complete)
        self.stat_partial.set_value(partial)
        self.stat_draft.set_value(draft)
        self.stat_avg_completeness.set_value(f"{avg_completeness:.0f}%")

    # ── DOSSIER GENERATION ───────────────────────────────────
    def generate_dossier(self):
        project_id = self.cmb_project.currentData()
        line_number = self.txt_line.text().strip()

        if not project_id:
            QMessageBox.warning(
                self, "Validation Error",
                "Please select a project first."
            )
            return

        if not line_number:
            QMessageBox.warning(
                self, "Validation Error",
                "Please enter a line number."
            )
            self.txt_line.setFocus()
            return

        reply = QMessageBox.question(
            self, "Confirm Generation",
            f"Generate dossier for line:\n\n"
            f"  Line: {line_number}\n"
            f"  Project: {self.cmb_project.currentText()}\n\n"
            f"Continue?",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.Yes,
        )
        if reply != QMessageBox.StandardButton.Yes:
            return

        # ✅ FIXED: cleanup previous thread
        if self._generator_thread is not None:
            try:
                if self._generator_thread.isRunning():
                    self._generator_thread.wait(2000)
                self._generator_thread.deleteLater()
            except Exception:
                pass
            self._generator_thread = None

        self.btn_generate.setEnabled(False)
        self.btn_generate.setText("⏳ Generating...")
        self.progress_widget.setVisible(True)
        self.progress_bar.setValue(0)

        username = getattr(self.session, "username", "admin")

        self._generator_thread = DossierGeneratorThread(
            self.svc, project_id, line_number, username
        )
        self._generator_thread.progress.connect(self._on_generation_progress)
        self._generator_thread.finished.connect(self._on_generation_finished)
        self._generator_thread.error.connect(self._on_generation_error)
        self._generator_thread.start()

    def _on_generation_progress(self, value: int, message: str):
        self.progress_bar.setValue(value)
        self.progress_label.setText(message)
        self._set_status(message)

    def _on_generation_finished(self, result: dict):
        self.btn_generate.setEnabled(True)
        self.btn_generate.setText("⚡ Generate Dossier")

        QTimer.singleShot(
            1500, lambda: self.progress_widget.setVisible(False)
        )

        self.txt_line.clear()
        self.refresh()

        dossier_num = result.get("dossier_number", "N/A")
        completeness = result.get("completeness_pct", 0)
        path = result.get("path", "N/A")

        QMessageBox.information(
            self, "✅ Dossier Generated Successfully",
            f"Dossier has been generated:\n\n"
            f"  📋 Number: {dossier_num}\n"
            f"  📊 Completeness: {completeness}%\n"
            f"  📁 Path: {path}\n\n"
            f"The dossier is now available in the table."
        )
        self._set_status(f"Dossier {dossier_num} generated successfully")

        if self._generator_thread is not None:
            self._generator_thread.deleteLater()
            self._generator_thread = None

    def _on_generation_error(self, error_message: str):
        self.btn_generate.setEnabled(True)
        self.btn_generate.setText("⚡ Generate Dossier")
        self.progress_widget.setVisible(False)

        QMessageBox.critical(
            self, "❌ Dossier Generation Error",
            f"Failed to generate dossier:\n\n{error_message}\n\n"
            f"Please check the line number and try again."
        )
        self._set_status(f"Generation failed: {error_message}")

        if self._generator_thread is not None:
            self._generator_thread.deleteLater()
            self._generator_thread = None

    # ── DELETE ───────────────────────────────────────────────
    def delete_selected(self):
        selected_rows = self.table.selectionModel().selectedRows()
        if not selected_rows:
            QMessageBox.warning(
                self, "No Selection",
                "Please select one or more dossiers to delete."
            )
            return

        selected_ids = []
        selected_names = []
        for index in selected_rows:
            row = index.row()
            dossier_id = self.table.item(row, 0)
            dossier_name = self.table.item(row, 1)
            if dossier_id:
                selected_ids.append(int(dossier_id.text()))
            if dossier_name:
                selected_names.append(dossier_name.text())

        if not selected_ids:
            return

        names_text = "\n".join(f"  • {name}" for name in selected_names[:10])
        if len(selected_names) > 10:
            names_text += f"\n  ... and {len(selected_names) - 10} more"

        reply = QMessageBox.warning(
            self, "⚠️ Confirm Delete",
            f"Are you sure you want to delete {len(selected_ids)} dossier(s)?\n\n"
            f"{names_text}\n\n"
            f"This action cannot be undone.",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
            QMessageBox.StandardButton.No,
        )
        if reply != QMessageBox.StandardButton.Yes:
            return

        try:
            deleted_count = 0
            with self.db.session_scope() as s:
                for dossier_id in selected_ids:
                    # ✅ FIXED: SQLAlchemy 2.0 — use session.get()
                    dossier = s.get(TurnoverDossier, dossier_id)
                    if dossier:
                        s.delete(dossier)
                        deleted_count += 1
                s.commit()

            self.refresh()
            QMessageBox.information(
                self, "✅ Deleted",
                f"Successfully deleted {deleted_count} dossier(s)."
            )
            self._set_status(f"Deleted {deleted_count} dossier(s)")
        except Exception as e:
            logger.exception("Delete failed.")
            QMessageBox.critical(
                self, "Delete Error",
                f"Failed to delete dossiers:\n{str(e)}"
            )

    # ── EXPORT ───────────────────────────────────────────────
    def export_csv(self):
        if self.table.rowCount() == 0:
            QMessageBox.warning(self, "No Data", "There is no data to export.")
            return

        default_name = (
            f"turnover_dossiers_"
            f"{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
        )
        file_path, _ = QFileDialog.getSaveFileName(
            self, "Export CSV", default_name,
            "CSV Files (*.csv);;All Files (*)"
        )
        if not file_path:
            return

        try:
            with open(file_path, "w", newline="", encoding="utf-8-sig") as f:
                writer = csv.writer(f)
                headers = [
                    TABLE_COLUMNS[i]
                    for i in range(len(TABLE_COLUMNS)) if i != 0
                ]
                writer.writerow(headers)

                for row in range(self.table.rowCount()):
                    row_data = []
                    for col in range(len(TABLE_COLUMNS)):
                        if col == 0:
                            continue
                        item = self.table.item(row, col)
                        value = item.text() if item else ""
                        if col == 4:
                            value = f"{value}%"
                        row_data.append(value)
                    writer.writerow(row_data)

            QMessageBox.information(
                self, "✅ Export Complete",
                f"Data exported successfully to:\n{file_path}\n\n"
                f"Total rows: {self.table.rowCount()}"
            )
            self._set_status(f"Exported {self.table.rowCount()} rows to CSV")
        except Exception as e:
            logger.exception("CSV export failed.")
            QMessageBox.critical(
                self, "Export Error",
                f"Failed to export CSV:\n{str(e)}"
            )

