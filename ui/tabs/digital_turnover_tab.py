#  BACKGROUND WORKER
# ─────────────────────────────────────────────
class DossierGeneratorThread(QThread):
    """Background worker for dossier generation — UI stays responsive."""
    finished = pyqtSignal(dict)
    error = pyqtSignal(str)
    progress = pyqtSignal(int, str)

    def __init__(self, service, project_id, line_number, username):
        super().__init__()
        self.service = service
        self.project_id = project_id
        self.line_number = line_number
        self.username = username

    def run(self):
        try:
            self.progress.emit(10, "Initializing dossier generation...")
            self.progress.emit(30, "Collecting engineering data...")
            self.progress.emit(50, "Processing weld records...")
            self.progress.emit(70, "Compiling documents...")

            result = self.service.generate_line_dossier(
                self.project_id,
                self.line_number,
                self.username,
            )

            self.progress.emit(90, "Finalizing dossier...")
            self.progress.emit(100, "Complete!")
            self.finished.emit(result)

        except Exception as e:
            logger.exception("Dossier generation failed.")
            self.error.emit(str(e))


