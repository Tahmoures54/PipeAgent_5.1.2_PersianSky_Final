class ProgressBarDelegate(QStyledItemDelegate):
    """Renders an inline progress bar in the Completeness column."""

    def paint(self, painter, option, index):
        text = index.data(Qt.ItemDataRole.DisplayRole)
        if text is None:
            super().paint(painter, option, index)
            return

        try:
            value = int(str(text).replace("%", "").strip())
        except (ValueError, AttributeError):
            super().paint(painter, option, index)
            return

        painter.save()
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)

        rect = option.rect.adjusted(8, 6, -8, -6)

        if value >= 90:
            bar_color = QColor("#10b981")
            bg_color = QColor("#d1fae5")
        elif value >= 70:
            bar_color = QColor("#3b82f6")
            bg_color = QColor("#dbeafe")
        elif value >= 50:
            bar_color = QColor("#f59e0b")
            bg_color = QColor("#fef3c7")
        else:
            bar_color = QColor("#ef4444")
            bg_color = QColor("#fee2e2")

        painter.setBrush(QBrush(bg_color))
        painter.setPen(Qt.PenStyle.NoPen)
        painter.drawRoundedRect(rect, 4, 4)

        fill_width = int(rect.width() * value / 100)
        fill_rect = rect.adjusted(0, 0, -(rect.width() - fill_width), 0)
        painter.setBrush(QBrush(bar_color))
        painter.drawRoundedRect(fill_rect, 4, 4)

        painter.setPen(QPen(QColor("#1e293b")))
        font = painter.font()
        font.setBold(True)
        font.setPointSize(9)
        painter.setFont(font)
        painter.drawText(rect, Qt.AlignmentFlag.AlignCenter, f"{value}%")

        painter.restore()


